"""Install the pinned libraries from pyproject.toml, then refresh requirements.lock.

Run with the project's own Python:  .venv/bin/python scripts/install_deps.py

Why this script exists: pyproject.toml is the one place versions are chosen.
requirements.lock records every library actually installed (including the ones
our libraries pull in), so CI and future installs get exactly the same set.
"""

import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    if sys.prefix == sys.base_prefix:
        sys.exit("Run this with the project's .venv Python, not the system one.")

    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    pins = project["dependencies"] + project["optional-dependencies"]["dev"]

    unpinned = [p for p in pins if "==" not in p]
    if unpinned:
        sys.exit(f"Every library must use an exact == version. Not pinned: {unpinned}")

    subprocess.run([sys.executable, "-m", "pip", "install", *pins], check=True)

    frozen = subprocess.run(
        [sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    header = "# Generated by scripts/install_deps.py. Do not edit by hand.\n"
    (ROOT / "requirements.lock").write_text(header + frozen)
    print(f"Installed {len(pins)} pinned libraries; wrote requirements.lock.")


if __name__ == "__main__":
    main()
